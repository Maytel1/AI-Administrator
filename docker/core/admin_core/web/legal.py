# Редакция документов: обновлять при правках текста.
LEGAL_REVISION = "10.11.2026"


def _requisites_block() -> str:
    """Реквизиты исполнителя из env; пустые поля не выдумываем — показываем подсказку."""
    req = requisites()

    def field(label: str, key: str) -> str:
        value = req.get(key) or f"(задайте BILLING_{key.upper()})"
        return f"<li><b>{esc(label)}:</b> {esc(value)}</li>"

    return (
        "<ul>"
        + field("Получатель", "legal_name")
        + field("ИНН", "inn")
        + field("КПП", "kpp")
        + field("Банк", "bank")
        + field("Р/с", "account")
        + "</ul>"
    )


def _doc_page(title: str, body: str) -> str:
    """Каркас публичного документа: свои стили (``.doc`` в static.css), без панели."""
    return (
        '<!DOCTYPE html><html lang="ru"><head><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width,initial-scale=1">'
        f"<title>{esc(title)} — Дежурный24</title>"
        '<link rel="stylesheet" href="/static.css"></head><body>'
        '<div class="doc">'
        '<div class="meta"><a href="/login">← Ко входу</a></div>'
        f"<h1>{esc(title)}</h1>{body}"
        f'<p class="meta">Редакция от {esc(LEGAL_REVISION)}. '
        "Изменения публикуются на этой странице с указанной датой.</p>"
        "</div></body></html>"
    )


